/* ━━━ Imports > ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━ */


 export default class UserMockGateway implements UserGateway {

  private static readonly MUST_SIMULATE_ERROR: boolean = false;


  public constructor(
    private readonly mockDataSource: MockDataSource
  ) {}

  public async retrieveOneByEmailAddressIfExists(targetEmailAddress: string): Promise<User | null> {
    return MockGatewayHelper.simulateDataRetrieving({
      requestParameters: targetEmailAddress,
      getResponseData:
          (): User | null => this.mockDataSource.retrieveUserByEmailAddressIfExists(targetEmailAddress),
      minimalPendingPeriod__seconds: 1,
      maximalPendingPeriod__seconds: 5,
      mustSimulateError: UserMockGateway.MUST_SIMULATE_ERROR,
      gatewayName: "UserMockGateway",
      transactionName: "retrieveOneByEmailAddressIfExists"
    });
  }

}
