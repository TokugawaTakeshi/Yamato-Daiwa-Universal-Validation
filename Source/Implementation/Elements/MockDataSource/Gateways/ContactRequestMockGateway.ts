import { MockGatewayHelper } from "@yamato-daiwa/es-extensions";
/* ━━━ Imports > ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━ */


export default class ContactRequestMockGateway implements ContactRequestGateway {

  private static readonly MUST_SIMULATE_ERROR: boolean = false;


  public constructor(
    private readonly mockDataSource: MockDataSource
  ) {}


  public async submitLegitimateOne(
    requestData: ContactRequestGateway.LegitimateContactRequestSubmitting.RequestData
  ): Promise<ContactRequest.ID> {
    return MockGatewayHelper.simulateDataSubmitting({
      requestData,
      getResponseData: (): ContactRequest.ID => this.mockDataSource.submitLegitimateContactRequest(requestData),
      mustSimulateError: ContactRequestMockGateway.MUST_SIMULATE_ERROR,
      gatewayName: "ContactRequestMockGateway",
      transactionName: "submitLegitimateOne"
    });
  }

  public async recordInvalidContactRequestSubmittingAttempt(
    requestData: ContactRequestGateway.InvalidContactRequestSubmittingRecording.RequestData
  ): Promise<void> {
    return MockGatewayHelper.simulateDataSubmitting({
      requestData,
      getResponseData: (): void => { this.mockDataSource.recordInvalidContactRequestSubmittingAttempt(requestData); },
      mustSimulateError: ContactRequestMockGateway.MUST_SIMULATE_ERROR,
      gatewayName: "ContactRequestMockGateway",
      transactionName: "recordInvalidContactRequestSubmittingAttempt"
    });
  }

}
