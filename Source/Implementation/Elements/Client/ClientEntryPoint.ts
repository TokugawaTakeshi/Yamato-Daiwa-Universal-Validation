import { createPinia } from "pinia";
import { AJAX_Service, FetchAPI_Service } from "@yamato-daiwa/es-extensions";
import ClientDependenciesInjector from "@Client/DependenciesInjection/ClientDependenciesInjector";
import AccessControlAJAX_Gateway from "@Client/Gateways/AccessControlAJAX_Gateway";
